package io.github.basekt.data

import io.github.basekt.schema.Model
import io.github.basekt.schema.Resource

/**
 * Typed access to a [Model]'s records in [source]: every call takes and returns [T], converted through [T]'s
 * serializer, over the same [DataSource] calls dynamic code makes.
 *
 * A repository is data access. It doesn't check permissions, validate, set automatic fields or run the server's
 * hooks: use it in trusted server code such as seeding, jobs and hooks themselves (pass a hook's transaction as
 * [source]). Requests from callers go through the server's resource service instead.
 */
public class Repository<T>(
    /** The model whose records this repository reads and writes. */
    public val model: Model<T>,
    /** Where the records live. */
    private val source: DataSource,
) {
    private val resource: Resource get() = model.resource

    /** Returns the record with [id], or `null` if there isn't one. */
    public suspend fun get(id: String): T? = source.get(resource, id)?.let(model::fromRecord)

    /** Returns the records whose ids are in [ids], keyed by id. Ids with no record are absent. */
    public suspend fun getMany(ids: Collection<String>): Map<String, T> =
        source.getMany(resource, ids).mapValues { model.fromRecord(it.value) }

    /** Returns one page of records that match [block]'s query. */
    public suspend fun list(block: TypedQuery<T>.() -> Unit = {}): TypedPage<T> {
        val page = source.list(resource, query(block))
        return TypedPage(page.items.map(model::fromRecord), page.nextCursor)
    }

    /** Creates [value] and returns it as stored, with its id. A `null` or empty id is generated by the source. */
    public suspend fun create(value: T): T = model.fromRecord(source.create(resource, model.toRecord(value)))

    /**
     * Replaces every field of the record with [id] by [value]'s, and returns it as stored, or `null` if there is no
     * such record. [value]'s own id is ignored.
     */
    public suspend fun update(id: String, value: T): T? =
        source.update(resource, id, model.toRecord(value) - Resource.ID)?.let(model::fromRecord)

    /** Deletes the record with [id]. Returns `false` if there wasn't one. */
    public suspend fun delete(id: String): Boolean = source.delete(resource, id)

    /** Returns the transport-neutral [Query] that [block] describes. */
    public fun query(block: TypedQuery<T>.() -> Unit): Query = TypedQuery(model).apply(block).build()
}

/** One page of typed records, and the cursor of the next page. */
public data class TypedPage<T>(
    /** The records, in the query's order. */
    val items: List<T>,
    /** The cursor of the next page, or `null` if this is the last one. */
    val nextCursor: String?,
) {
    /** Whether there is a next page. */
    val hasNext: Boolean get() = nextCursor != null
}

